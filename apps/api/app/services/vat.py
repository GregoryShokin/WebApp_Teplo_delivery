"""НДС платежа: ставка, выделение налога из итога и хвост назначения платежа.

Назначение платежа обязано называть налог («в т.ч. НДС 22% — 1 439,90») или прямо говорить
«Без НДС»: это читают банк и налоговая. У платёжки по СЧЁТУ налог берётся с накладной
(``counterparty_payments._aggregate_vat``), у платежа из окна «Новый платёж» счёта нет —
ставку называет человек, а сумма выделяется из итога платежа.

Модуль намеренно лёгкий (только ``re`` и ``decimal``): его импортируют и схемы, и сервисы.
"""

from __future__ import annotations

import re
from decimal import ROUND_HALF_UP, Decimal

# Ставки, из которых окно «Новый платёж» даёт выбрать: действующая основная (22 %), прежняя
# основная (20 % — по ней до сих пор выставлены счета, подписанные до 2026 года), льготная
# 10 % и упрощённые 7 % / 5 %. Нуля здесь нет намеренно: «НДС 0 %» и «без НДС» банк читает
# одинаково, а разница видна только в самом документе — платёжке хватает «Без НДС.».
VAT_RATES: tuple[str, ...] = ("22", "20", "10", "7", "5")


def normalize_vat_rate(rate: str | None) -> str:
    """Ставка голыми цифрами («22 %» → «22»). Пусто, мусор или ноль → «» (платёж без НДС)."""
    digits = re.sub(r"\D", "", rate or "")
    return "" if not digits or int(digits) <= 0 else str(int(digits))


def validate_vat_rate(rate: str | None) -> str | None:
    """Проверка ставки на входе API. Пусто → ``None`` (без НДС).

    Список ставок здесь НЕ жёсткий: платёж 2026 года может закрывать счёт, выставленный по
    прежней ставке, а завтра появится новая — ломать приём платежей из-за этого нельзя.
    Отсекается только заведомая чушь (ноль уже съеден нормализацией, сотня и выше — ошибка
    ввода: столько налога в сумме платежа не бывает).
    """
    clean = normalize_vat_rate(rate)
    if not clean:
        return None
    if int(clean) >= 100:
        raise ValueError("Ставка НДС должна быть от 1 до 99 %")
    return clean


def vat_amount_for_rate(total: Decimal, rate: str | None) -> Decimal:
    """Налог «в том числе» из ИТОГОВОЙ суммы платежа: сумма × ставка / (100 + ставка).

    Платёж всегда назначается итогом — эту сумму списывает банк, — поэтому налог из неё
    выделяется, а не начисляется сверху. Начислить сверху значило бы отправить в банк не ту
    сумму, которую согласовали с получателем.
    """
    clean = normalize_vat_rate(rate)
    if not clean:
        return Decimal("0.00")
    percent = Decimal(clean)
    total = Decimal(str(total or 0)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return (total * percent / (Decimal(100) + percent)).quantize(
        Decimal("0.01"), rounding=ROUND_HALF_UP
    )
