"""Единственная точка, где берётся «сегодня» по Москве.

ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ. Код, который читает системную дату прямо в месте использования,
нельзя проверить: тест зависит от того, какое сегодня число у того, кто его запустил.
01.08.2026 это выстрелило — девять тестов кассы покраснели на пустом месте, потому что первое
число оказалось днём выплаты, а выдача аванса в день выплаты заблокирована по методологии.
Код был исправен, календарь — нет.

ПОЧЕМУ ЧЕРЕЗ МОДУЛЬ, А НЕ ПРЯМЫМ ИМПОРТОМ. Вызывать надо ``clock.moscow_today()``, а не
``from app.services.clock import moscow_today``. Разница решающая для подмены: при импорте имя
копируется в модуль-потребитель, и подмена ``app.services.clock.moscow_today`` до него уже не
дойдёт. Обращение через модуль ищет атрибут в момент ВЫЗОВА — поэтому одной подмены хватает на
всех, включая тесты, которые держат ссылку на ``kassa_today``.

ОХВАТ. Сейчас сюда переведены две функции — ``kassa_today`` и ``advance_today``, — то есть
ровно те, от которых зависят тесты кассы. В коде остаётся ещё около тридцати мест с
``datetime.now(MOSCOW_TZ).date()``; переводить их скопом в рамках починки тестов было бы
подменой задачи. Переводить по мере того, как каждое из них начнёт мешать проверяться.
"""

from __future__ import annotations

from datetime import date, datetime
from zoneinfo import ZoneInfo

MOSCOW_TZ = ZoneInfo("Europe/Moscow")


def moscow_today() -> date:
    """Сегодняшняя дата по Москве. Единственное место, которое смотрит на системные часы."""
    return datetime.now(MOSCOW_TZ).date()


def as_moscow(value: datetime) -> datetime:
    """Наивный ``datetime`` от клиента — это МОСКОВСКОЕ стенное время, а не UTC.

    Поля ввода ``<input type="datetime-local">`` отдают строку без зоны («2026-08-20T15:16»).
    Pydantic превращает её в наивный datetime, а колонки у нас ``timestamptz``, и контейнер API
    живёт в UTC — значит наивное значение уезжает в базу как UTC. Оператор набрал 15:16 по
    московским часам, база записала 15:16 по Гринвичу, витрина показала 18:16.

    Так на проде разъехались все 190 накладных и чеков с ``issued_at`` (найдено 20.08.2026:
    накладная 515287 создана в 15:17 МСК, а «выписана» в 18:16 — на три часа позже собственного
    создания). Дату документа это не искажало (``.date()`` от наивного значения = набранная
    дата), а вот инстант — да, и по нему подбирается банковская операция под чек.

    Уже локализованное значение не трогаем: клиент вправе прислать смещение явно.
    """
    return value.replace(tzinfo=MOSCOW_TZ) if value.tzinfo is None else value
