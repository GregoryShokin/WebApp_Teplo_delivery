def registry_to_payload(sources: tuple[TaxSource, ...] = DEFAULT_SOURCES) -> dict[str, Any]:
    """Реестр в виде, пригодном для хранения в ``app_setting.value``."""
    return {"version": 1, "sources": [asdict(s) for s in sources]}


async def load_source_registry(session: AsyncSession) -> dict[str, Any]:
    """Прочитать реестр из настроек. Если не установлен — вернуть значение по умолчанию.

    Fallback намеренный: модуль обязан считать и на свежей базе, где сид ещё не прогонялся.
    """
    stored = await session.scalar(
        select(AppSetting.value).where(AppSetting.key == SOURCE_REGISTRY_KEY)
    )
    if not stored:
        return registry_to_payload()
    return stored


def weakest_links(payload: dict[str, Any]) -> list[dict[str, Any]]:
    """Входы, которым нельзя доверять как первичным. Показываются на странице «Налоги»."""
    return [
        item
        for item in payload.get("sources", [])
        if item.get("confidence") in ("reconstructed", "missing")
    ]
