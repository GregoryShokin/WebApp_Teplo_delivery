@dataclass(frozen=True)
class AssetLineKey:
    """Ключ строки основных средств.

    Ключуемся по ИМЕНИ строки, а не по идентификатору категории: у регистра две разные строки
    имеют пустую категорию — «Не работающее оборудование» (собирается по статусу карточки) и
    «Без категории» (карточки, которым категорию не проставили). По идентификатору они
    схлопнулись бы в одну, и одна из них потерялась бы при заморозке.
    """

    line_name: str

    @property
    def code(self) -> str:
        slug = "".join(ch if ch.isalnum() else "_" for ch in self.line_name.lower())
        return f"os_{slug.strip('_')[:48]}"


