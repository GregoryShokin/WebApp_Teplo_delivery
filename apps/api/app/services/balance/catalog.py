"""Справочник строк баланса: что показываем и чем каждая строка закрывается.

ПОЧЕМУ КОНСТАНТА В КОДЕ, А НЕ ТАБЛИЦА. У балансовой строки источник — это ВЫЗОВ ФУНКЦИИ, а не
правило в данных: «Накопительный фонд» есть ``build_staff_balance_as_of(...).fund_total``, а
«Запасы» — сумма складских фактов месяца. В строку таблицы такое не записать, значит новая строка
всё равно потребует правки кода, и таблица дала бы вторую копию того же знания плюс миграцию на
каждую перестановку. У строк ОПиУ ситуация обратная — там разметку статей действительно правит
владелец руками, поэтому там таблица уместна, а здесь нет.

ЧЕГО ЗДЕСЬ НЕТ. Одиннадцать строк основных средств не перечислены: они приходят из своего
регистра как есть, вместе с именами категорий, и дублировать их здесь значило бы завести второй
справочник категорий, который разойдётся с первым при первом же переименовании.

ПУСТЫЕ СТРОКИ ВИДНЫ. Строка, которую заполнить нечем, остаётся в справочнике с явным статусом —
иначе следующий читатель решит, что её забыли подключить. Статусы различают три разные пустоты:
``zero_confirmed`` — владелец подтвердил, что величина нулевая (кредитов нет);
``manual`` — источника нет, но величина бывает ненулевой, её вводит человек с основанием;
``not_applicable`` — к этой форме бизнеса неприменимо (уставный капитал у ИП).
"""

