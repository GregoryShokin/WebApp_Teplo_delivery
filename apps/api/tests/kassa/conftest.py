"""Тесты кассы живут в закреплённом «сегодня», а не в том, которое у запускающего.

ПОЧЕМУ. Правила кассы и аванса завязаны на календарь: день выплаты блокирует выдачу аванса,
править проводку можно только в день создания. Пока «сегодня» бралось из системных часов,
результат прогона зависел от того, какое сегодня число. 01.08.2026 это и случилось: девять
тестов покраснели разом, потому что первое число оказалось днём выплаты. Код был исправен —
календарь нет, и полдня ушло на доказательство, что дело не в правках.

ДАТА ВЫБРАНА НЕ СЛУЧАЙНО. 6 июля 2026 — середина полумесячного периода: не первое и не
пятнадцатое, то есть заведомо не день выплаты ни у окладников, ни у производства. Тесты,
которые проверяют поведение ИМЕННО в день выплаты, закрепляют свою дату сами — фикстура
им не мешает, у неё обычный ``monkeypatch``.

ПОДМЕНА ОДНА НА ВСЁ. Патчится ``clock.moscow_today`` — общий источник, к которому обращаются и
``kassa_today``, и ``advance_today``. Патчить сами эти функции было бы недостаточно: тестовые
модули импортируют ``kassa_today`` по имени, и подмена атрибута в сервисе до их копии уже не
дошла бы. Подробности — в докстринге ``app.services.clock``.
"""

from __future__ import annotations

from datetime import date

import pytest

from app.services import clock

# Середина периода: не 1-е и не 15-е.
PINNED_TODAY = date(2026, 7, 6)


@pytest.fixture(autouse=True)
def pinned_today(monkeypatch: pytest.MonkeyPatch) -> date:
    """Закрепить «сегодня» для всего пакета тестов кассы.

    Автоприменяемая сознательно: календарная зависимость здесь не у отдельных тестов, а у
    всего модуля, и подключать фикстуру вручную значило бы ждать, пока следующий забытый тест
    покраснеет в первое число.
    """
    monkeypatch.setattr(clock, "moscow_today", lambda: PINNED_TODAY)
    return PINNED_TODAY
